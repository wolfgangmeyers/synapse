-- 048 is reserved for the separately owned archive schema. This migration is
-- intentionally the next registry entry and adds only the Phase 2A bridge
-- store. No existing managed rows are rewritten.
CREATE TABLE managed_bridges (
  bridge_id TEXT PRIMARY KEY CHECK (length(CAST(bridge_id AS BLOB)) BETWEEN 1 AND 128),
  agent_id TEXT NOT NULL UNIQUE REFERENCES managed_agents(agent_id) ON DELETE CASCADE,
  verifier BLOB NOT NULL CHECK (length(verifier) = 32),
  enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  revoked INTEGER NOT NULL DEFAULT 0 CHECK (revoked IN (0,1)),
  fence_agent_id TEXT NOT NULL,
  fence_pi_session_id TEXT NOT NULL,
  fence_session_epoch INTEGER NOT NULL CHECK (fence_session_epoch >= 1),
  fence_process_pid INTEGER NOT NULL CHECK (fence_process_pid > 0),
  fence_process_start_marker TEXT NOT NULL,
  fence_process_incarnation TEXT NOT NULL,
  fence_runtime_generation TEXT NOT NULL,
  fence_manifest_revision INTEGER NOT NULL CHECK (fence_manifest_revision >= 1),
  fence_manifest_hash TEXT NOT NULL CHECK (length(fence_manifest_hash)=64 AND fence_manifest_hash=lower(fence_manifest_hash) AND fence_manifest_hash NOT GLOB '*[^0-9a-f]*'),
  fence_hash TEXT NOT NULL CHECK (length(fence_hash)=64 AND fence_hash=lower(fence_hash) AND fence_hash NOT GLOB '*[^0-9a-f]*'),
  command_next_seq TEXT NOT NULL DEFAULT '1',
  command_acked_seq TEXT NOT NULL DEFAULT '0',
  command_floor TEXT NOT NULL DEFAULT '1',
  event_admitted_next TEXT NOT NULL DEFAULT '1',
  event_admitted_floor TEXT NOT NULL DEFAULT '1',
  event_applied_next TEXT NOT NULL DEFAULT '1',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  CHECK (fence_agent_id = agent_id),
  CHECK (revoked = 0 OR enabled = 0),
  CHECK (length(CAST(command_next_seq AS BLOB)) BETWEEN 1 AND 20),
  CHECK (length(CAST(command_acked_seq AS BLOB)) BETWEEN 1 AND 20),
  CHECK (length(CAST(command_floor AS BLOB)) BETWEEN 1 AND 20),
  CHECK (length(CAST(event_admitted_next AS BLOB)) BETWEEN 1 AND 20),
  CHECK (length(CAST(event_admitted_floor AS BLOB)) BETWEEN 1 AND 20),
  CHECK (length(CAST(event_applied_next AS BLOB)) BETWEEN 1 AND 20)
);

CREATE TABLE managed_bridge_commands (
  bridge_id TEXT NOT NULL REFERENCES managed_bridges(bridge_id) ON DELETE CASCADE,
  seq TEXT NOT NULL CHECK (length(CAST(seq AS BLOB)) BETWEEN 1 AND 20),
  request_id TEXT NOT NULL,
  command_name TEXT NOT NULL,
  payload BLOB NOT NULL CHECK (length(payload) BETWEEN 1 AND 32768),
  payload_hash TEXT NOT NULL CHECK (length(payload_hash)=64 AND payload_hash=lower(payload_hash) AND payload_hash NOT GLOB '*[^0-9a-f]*'),
  fence_agent_id TEXT NOT NULL,
  fence_pi_session_id TEXT NOT NULL,
  fence_session_epoch INTEGER NOT NULL CHECK (fence_session_epoch >= 1),
  fence_process_pid INTEGER NOT NULL CHECK (fence_process_pid > 0),
  fence_process_start_marker TEXT NOT NULL,
  fence_process_incarnation TEXT NOT NULL,
  fence_runtime_generation TEXT NOT NULL,
  fence_manifest_revision INTEGER NOT NULL CHECK (fence_manifest_revision >= 1),
  fence_manifest_hash TEXT NOT NULL CHECK (length(fence_manifest_hash)=64 AND fence_manifest_hash=lower(fence_manifest_hash) AND fence_manifest_hash NOT GLOB '*[^0-9a-f]*'),
  fence_hash TEXT NOT NULL CHECK (length(fence_hash)=64 AND fence_hash=lower(fence_hash) AND fence_hash NOT GLOB '*[^0-9a-f]*'),
  state TEXT NOT NULL CHECK (state IN ('queued','acked','unknown')),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  acked_at TEXT,
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 1 AND 32768),
  PRIMARY KEY (bridge_id, seq),
  UNIQUE (bridge_id, request_id, command_name)
);
CREATE INDEX managed_bridge_commands_state_idx ON managed_bridge_commands(bridge_id, state, seq);

CREATE TABLE managed_bridge_events (
  bridge_id TEXT NOT NULL REFERENCES managed_bridges(bridge_id) ON DELETE CASCADE,
  seq TEXT NOT NULL CHECK (length(CAST(seq AS BLOB)) BETWEEN 1 AND 20),
  event_id TEXT NOT NULL,
  event_name TEXT NOT NULL,
  payload BLOB NOT NULL CHECK (length(payload) BETWEEN 1 AND 32768),
  payload_hash TEXT NOT NULL CHECK (length(payload_hash)=64 AND payload_hash=lower(payload_hash) AND payload_hash NOT GLOB '*[^0-9a-f]*'),
  fence_agent_id TEXT NOT NULL,
  fence_pi_session_id TEXT NOT NULL,
  fence_session_epoch INTEGER NOT NULL CHECK (fence_session_epoch >= 1),
  fence_process_pid INTEGER NOT NULL CHECK (fence_process_pid > 0),
  fence_process_start_marker TEXT NOT NULL,
  fence_process_incarnation TEXT NOT NULL,
  fence_runtime_generation TEXT NOT NULL,
  fence_manifest_revision INTEGER NOT NULL CHECK (fence_manifest_revision >= 1),
  fence_manifest_hash TEXT NOT NULL CHECK (length(fence_manifest_hash)=64 AND fence_manifest_hash=lower(fence_manifest_hash) AND fence_manifest_hash NOT GLOB '*[^0-9a-f]*'),
  fence_hash TEXT NOT NULL CHECK (length(fence_hash)=64 AND fence_hash=lower(fence_hash) AND fence_hash NOT GLOB '*[^0-9a-f]*'),
  state TEXT NOT NULL CHECK (state IN ('admitted','applied')),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  admitted_at TEXT NOT NULL,
  applied_at TEXT,
  size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 1 AND 32768),
  PRIMARY KEY (bridge_id, seq),
  UNIQUE (bridge_id, event_id)
);
CREATE INDEX managed_bridge_events_state_idx ON managed_bridge_events(bridge_id, state, seq);
