// IR-003, IR-006, IR-008, IR-012: authorization uses the current definition
// and binding generation, while explicit legacy edges remain independent.
func TestAuthorizedWorkflowTransition(t *testing.T) {
	ctx := context.Background()
	s, agent := readinessSourceFixture(t)
	wf, err := s.CreateWorkflow(ctx, WorkflowRequest{Name: "flow"})
	require.NoError(t, err)
	other, err := s.CreateWorkflow(ctx, WorkflowRequest{Name: "other"})
	require.NoError(t, err)
	a, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "A", WorkflowID: &wf.ID})
	require.NoError(t, err)
	b, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "B", WorkflowID: &wf.ID})
	require.NoError(t, err)
	c, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "C", WorkflowID: &other.ID})
	require.NoError(t, err)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET transitions_json=? WHERE id=?`, `[{"target_state_id":"`+b.ID+`"}]`, a.ID)
	require.NoError(t, err)
	require.NoError(t, s.SetManagedAgentActiveWorkflowWithVariables(ctx, agent.AgentID, &wf.ID, &a.ID, nil))
	snap, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, a.ID, "missing")
	require.ErrorContains(t, err, "allowed targets: B")
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, a.ID, "b")
	require.NoError(t, err)
	snapB, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snapB.Generation, b.ID, a.ID)
	require.ErrorContains(t, err, "no outgoing transitions")
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET allow_implicit_return=1 WHERE id=?`, b.ID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snapB.Generation, b.ID, "missing")
	require.ErrorContains(t, err, "allowed targets: A")
	target, err := s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snapB.Generation, b.ID, "a")
	require.NoError(t, err)
	require.Equal(t, a.ID, target.ID)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, a.ID, b.ID)
	require.Error(t, err)
	now, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	require.Equal(t, b.ID, now.PredecessorID)
	// Explicit cross-workflow and self edges must work even with return disabled.
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET transitions_json=? WHERE id=?`, `[{"target_state_id":"`+c.ID+`"},{"target_state_id":"`+a.ID+`"}]`, a.ID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, now.Generation, a.ID, a.ID)
	require.NoError(t, err)
	now, err = s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, now.Generation, a.ID, c.ID)
	require.NoError(t, err)
	now, err = s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET allow_implicit_return=1 WHERE id=?`, c.ID)
	require.NoError(t, err)
	// The previous state belongs to the active workflow and is eligible here.
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, now.Generation, c.ID, a.ID)
	require.NoError(t, err)
	now, err = s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET transitions_json='[]', allow_implicit_return=1 WHERE id=?`, a.ID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, now.Generation, a.ID, c.ID)
	require.Error(t, err)
}

func TestWorkflowGuidanceTargetsRespectBinding(t *testing.T) {
	ctx := context.Background()
	s, agent := readinessSourceFixture(t)
	wf, err := s.CreateWorkflow(ctx, WorkflowRequest{Name: "flow"})
	require.NoError(t, err)
	yes := true
	b, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "B", WorkflowID: &wf.ID, AllowImplicitReturn: &yes})
	require.NoError(t, err)
	a, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "A", WorkflowID: &wf.ID, Transitions: []WorkflowTransitionConfig{{TargetStateID: b.ID}}})
	require.NoError(t, err)
	require.NoError(t, s.SetManagedAgentActiveWorkflowWithVariables(ctx, agent.AgentID, &wf.ID, &a.ID, nil))
	snap, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, a.ID, b.ID)
	require.NoError(t, err)
	guidance, err := s.WorkflowStateForGuidance(ctx, agent.AgentID, b)
	require.NoError(t, err)
	require.Len(t, guidance.Transitions, 1)
	require.Equal(t, a.ID, guidance.Transitions[0].TargetStateID)
	require.Empty(t, b.Transitions)
	// A configuration edit after arrival is reflected in newly generated guidance.
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET allow_implicit_return=0 WHERE id=?`, b.ID)
	require.NoError(t, err)
	b, err = s.GetWorkflowState(ctx, b.ID)
	require.NoError(t, err)
	guidance, err = s.WorkflowStateForGuidance(ctx, agent.AgentID, b)
	require.NoError(t, err)
	require.Empty(t, guidance.Transitions)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET allow_implicit_return=1 WHERE id=?`, b.ID)
	require.NoError(t, err)
	b, err = s.GetWorkflowState(ctx, b.ID)
	require.NoError(t, err)
	guidance, err = s.WorkflowStateForGuidance(ctx, agent.AgentID, b)
	require.NoError(t, err)
	require.Len(t, guidance.Transitions, 1)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET transitions_json=? WHERE id=?`, `[{"target_state_id":"`+a.ID+`"}]`, b.ID)
	require.NoError(t, err)
	b, err = s.GetWorkflowState(ctx, b.ID)
	require.NoError(t, err)
	guidance, err = s.WorkflowStateForGuidance(ctx, agent.AgentID, b)
	require.NoError(t, err)
	require.Len(t, guidance.Transitions, 1)
	require.NoError(t, s.SetManagedAgentActiveWorkflowWithVariables(ctx, agent.AgentID, &wf.ID, &b.ID, nil))
	b.Transitions = nil
	guidance, err = s.WorkflowStateForGuidance(ctx, agent.AgentID, b)
	require.NoError(t, err)
	require.Empty(t, guidance.Transitions)
}

func TestExplicitTransitionStopsBeforeUnrelatedLookups(t *testing.T) {
	ctx := context.Background()
	s, agent := readinessSourceFixture(t)
	wf, err := s.CreateWorkflow(ctx, WorkflowRequest{Name: "flow"})
	require.NoError(t, err)
	bad, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "bad", WorkflowID: &wf.ID})
	require.NoError(t, err)
	first, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: bad.ID, WorkflowID: &wf.ID})
	require.NoError(t, err)
	yes := true
	source, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "source", WorkflowID: &wf.ID, AllowImplicitReturn: &yes})
	require.NoError(t, err)
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET transitions_json=? WHERE id=?`, `[{"target_state_id":"`+first.ID+`"},{"target_state_id":"`+bad.ID+`"}]`, source.ID)
	require.NoError(t, err)
	require.NoError(t, s.SetManagedAgentActiveWorkflowWithVariables(ctx, agent.AgentID, &wf.ID, &source.ID, nil))
	_, err = s.db.ExecContext(ctx, `UPDATE managed_agents SET workflow_predecessor_state_id=? WHERE agent_id=?`, bad.ID, agent.AgentID)
	require.NoError(t, err)
	// An invalid later target also serves as the predecessor: neither may be read.
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET ui_pos_x='invalid' WHERE id=?`, bad.ID)
	require.NoError(t, err)
	snap, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	target, err := s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, source.ID, bad.ID)
	require.NoError(t, err)
	require.Equal(t, first.ID, target.ID, "first matching name wins over a later matching ID")
}

func TestExplicitTransitionSkipsUnreadableEarlierEdge(t *testing.T) {
	ctx := context.Background()
	s, agent := readinessSourceFixture(t)
	wf, err := s.CreateWorkflow(ctx, WorkflowRequest{Name: "flow"})
	require.NoError(t, err)
	bad, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "bad", WorkflowID: &wf.ID})
	require.NoError(t, err)
	good, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "good", WorkflowID: &wf.ID})
	require.NoError(t, err)
	source, err := s.CreateWorkflowState(ctx, WorkflowStateRequest{Name: "source", WorkflowID: &wf.ID, Transitions: []WorkflowTransitionConfig{{TargetStateID: bad.ID}, {TargetStateID: good.ID}}})
	require.NoError(t, err)
	require.NoError(t, s.SetManagedAgentActiveWorkflowWithVariables(ctx, agent.AgentID, &wf.ID, &source.ID, nil))
	_, err = s.db.ExecContext(ctx, `UPDATE workflow_states SET ui_pos_x='invalid' WHERE id=?`, bad.ID)
	require.NoError(t, err)
	snap, err := s.WorkflowBindingVersion(ctx, agent.AgentID)
	require.NoError(t, err)
	_, err = s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, source.ID, bad.ID)
	require.ErrorContains(t, err, "target workflow state")
	target, err := s.AuthorizeWorkflowTransition(ctx, agent.AgentID, snap.Generation, source.ID, "good")
	require.NoError(t, err)
	require.Equal(t, good.ID, target.ID)
}
